"""Package an agent-browser dashboard static export for include_bytes!."""
import gzip
import json
import shutil
import sys
from pathlib import Path

source = Path(sys.argv[1])
dest = Path(__file__).resolve().parent / "assets"
types = {".html": "text/html; charset=utf-8", ".js": "text/javascript", ".css": "text/css", ".ico": "image/x-icon"}
files = [source / "index.html", source / "favicon.ico", *sorted((source / "_next").rglob("*"))]
if not all(p.is_file() for p in files[:2]) or not any(p.suffix == ".js" for p in files):
    raise ValueError("Expected a complete Next.js static export")
if dest.exists():
    shutil.rmtree(dest)
dest.mkdir()
lines = ["// Generated by package.py", "pub fn asset(path: &str) -> Option<(&'static str, &'static [u8])> {", "    match path {"]
for file in files:
    if not file.is_file() or file.suffix not in types:
        continue
    path = file.relative_to(source).as_posix()
    compressed = dest / (path + ".gz")
    compressed.parent.mkdir(parents=True, exist_ok=True)
    compressed.write_bytes(gzip.compress(file.read_bytes(), mtime=0))
    lines.append(f'        {json.dumps(path)} => Some(("{types[file.suffix]}", include_bytes!("assets/{path}.gz"))),')
lines.extend(["        _ => None,", "    }", "}"])
(dest.parent / "assets.rs").write_text("\n".join(lines) + "\n")
